# Usage: gen-keyboard-keys.sh SYSTEMD_SOURCE_DIR SYSTEMD_BUILD_DIR > keyboard_keys.rs
#
# The table of key names the keyboard builtin accepts, as upstream's
# keyboard-keys-from-name.gperf (generate-keyboard-keys-gperf.sh) has them,
# with the values from upstream's bundled kernel headers.
set -eu
src=$1
build=$2
list=$build/src/udev/keyboard-keys-list.txt
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo '#include <stdio.h>'
    echo '#include <linux/input.h>'
    echo 'int main(void) {'
    while read -r k; do
        case $k in
            KEY_*) n=$(echo "${k#KEY_}" | tr 'A-Z' 'a-z')
                   echo "printf(\"    (b\\\"$n\\\", %d),\\n\", (int) $k);"
                   echo "printf(\"    (b\\\"$(echo "$k" | tr 'A-Z' 'a-z')\\\", %d),\\n\", (int) $k);" ;;
            *)     echo "printf(\"    (b\\\"$(echo "$k" | tr 'A-Z' 'a-z')\\\", %d),\\n\", (int) $k);" ;;
        esac
    done < "$list"
    echo 'return 0; }'
} > "$tmp/gen.c"
cc -I "$src/src/include/uapi" -o "$tmp/gen" "$tmp/gen.c"
echo '// SPDX-License-Identifier: LGPL-2.1-or-later'
echo '//! The key names of `keyboard-keys-from-name.gperf`, generated by'
echo '//! tools/gen-keyboard-keys.sh from upstream'"'"'s kernel headers.'
echo
echo '/// (name, key code).'
echo 'pub const KEYS: &[(&[u8], u16)] = &['
"$tmp/gen"
echo '];'
