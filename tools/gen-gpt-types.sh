# gen-gpt-types.sh - generate crates/shared/src/gpt_types.rs
#
# 20261116 - Created by Claude (claude.ai, Anthropic) - scottfk
#
# Usage: gen-gpt-types.sh SYSTEMD_SOURCE_DIR > gpt_types.rs
#
# C's gpt_partition_type_table (src/shared/gpt.c), in its order: the table
# rows are taken from gpt.c itself, the UUIDs from upstream's sd-gpt.h.
set -eu
src=$1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
# The rows between "gpt_partition_type_table[] = {" and its "{}".
sed -n '/^const GptPartitionType gpt_partition_type_table\[\] = {/,/^        {}$/p' "$src/src/shared/gpt.c" \
        | sed '1d;$d' > "$tmp/rows.h"
cat > "$tmp/g.c" <<CEOF
#include <stdio.h>
#include "systemd/sd-gpt.h"
#define ARCHITECTURE_ALPHA "alpha"
#define ARCHITECTURE_ARC "arc"
#define ARCHITECTURE_ARM "arm"
#define ARCHITECTURE_ARM64 "arm64"
#define ARCHITECTURE_IA64 "ia64"
#define ARCHITECTURE_LOONGARCH64 "loongarch64"
#define ARCHITECTURE_MIPS "mips"
#define ARCHITECTURE_MIPS64 "mips64"
#define ARCHITECTURE_MIPS_LE "mips-le"
#define ARCHITECTURE_MIPS64_LE "mips64-le"
#define ARCHITECTURE_PARISC "parisc"
#define ARCHITECTURE_PPC "ppc"
#define ARCHITECTURE_PPC64 "ppc64"
#define ARCHITECTURE_PPC64_LE "ppc64-le"
#define ARCHITECTURE_RISCV32 "riscv32"
#define ARCHITECTURE_RISCV64 "riscv64"
#define ARCHITECTURE_S390 "s390"
#define ARCHITECTURE_S390X "s390x"
#define ARCHITECTURE_TILEGX "tilegx"
#define ARCHITECTURE_X86 "x86"
#define ARCHITECTURE_X86_64 "x86-64"
#define _ARCHITECTURE_INVALID ""
#define native_architecture() "@NATIVE@"
#define ARCHITECTURE_SECONDARY "@SECONDARY@"
#define PARTITION_ROOT "Root"
#define PARTITION_ROOT_VERITY "RootVerity"
#define PARTITION_ROOT_VERITY_SIG "RootVeritySig"
#define PARTITION_USR "Usr"
#define PARTITION_USR_VERITY "UsrVerity"
#define PARTITION_USR_VERITY_SIG "UsrVeritySig"
#define PARTITION_ESP "Esp"
#define PARTITION_XBOOTLDR "Xbootldr"
#define PARTITION_SWAP "Swap"
#define PARTITION_HOME "Home"
#define PARTITION_SRV "Srv"
#define PARTITION_VAR "Var"
#define PARTITION_TMP "Tmp"
#define _PARTITION_DESIGNATOR_INVALID ""
typedef struct { sd_id128_t uuid; const char *name; const char *arch; const char *designator; } T;
$(sed -n '/^#define _GPT_ARCH_SEXTET/,/^$/p' "$src/src/shared/gpt.c")
static const T t[] = {
#include "$tmp/rows.h"
};
int main(void) {
        for (unsigned i = 0; i < sizeof t / sizeof t[0]; i++) {
                printf("    GptType { uuid: [");
                for (int j = 0; j < 16; j++)
                        printf("%s0x%02x", j ? ", " : "", t[i].uuid.bytes[j]);
                printf("], name: \"%s\", arch: \"%s\", designator: \"%s\" },\n", t[i].name, t[i].arch, t[i].designator);
        }
        return 0;
}
CEOF
for a in x86_64 i686; do
        case $a in x86_64) m=-m64 ;; i686) m=-m32 ;; esac
        cc $m -I "$src/src/include/uapi" -I "$src/src/systemd" -I "$src/src" -o "$tmp/g-$a" "$tmp/g.c" 2>/dev/null || cc -I "$src/src" -o "$tmp/g-$a" "$tmp/g.c"
done
echo "// SPDX-License-Identifier: LGPL-2.1-or-later"
echo "//! Generated by tools/gen-gpt-types.sh: \`gpt_partition_type_table\`."
echo "//! \"@NATIVE@\" and \"@SECONDARY@\" stand for native_architecture() and"
echo "//! ARCHITECTURE_SECONDARY of the build."
echo ""
echo "/// A \`GptPartitionType\` row: designator and arch are \"\" when invalid."
echo "#[derive(Debug, Clone, Copy, PartialEq, Eq)]"
echo "pub struct GptType {"
echo "    pub uuid: [u8; 16],"
echo "    pub name: &'static str,"
echo "    pub arch: &'static str,"
echo "    pub designator: &'static str,"
echo "}"
echo ""
echo "/// The table for x86-64 builds."
echo "#[cfg(target_arch = \"x86_64\")]"
echo "pub const GPT_TYPES: &[GptType] = &["
"$tmp/g-x86_64"
echo "];"
echo ""
echo "/// The table for x86 builds."
echo "#[cfg(target_arch = \"x86\")]"
echo "pub const GPT_TYPES: &[GptType] = &["
"$tmp/g-i686"
echo "];"
