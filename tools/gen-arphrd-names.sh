# gen-arphrd-names.sh - generate crates/shared/src/arphrd_names.rs
#
# 20261116 - Created by Claude (claude.ai, Anthropic) - scottfk
#
# Usage: gen-arphrd-names.sh SYSTEMD_SOURCE_DIR SYSTEMD_BUILD_DIR > arphrd_names.rs
#
# C's arphrd_to_name(): the reference build's arphrd-to-name.inc, with the
# values from upstream's bundled kernel headers.
set -eu
src=$1
build=$2
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cat > "$tmp/a.c" <<CEOF
#include <stdio.h>
#include <linux/if_arp.h>
#include "$build/src/basic/arphrd-to-name.inc"
int main(void) {
        for (int i = 0; i < 65536; i++)
                if (arphrd_to_name(i))
                        printf("    (%d, \"%s\"),\n", i, arphrd_to_name(i));
        return 0;
}
CEOF
cc -I "$src/src/include/uapi" -o "$tmp/a" "$tmp/a.c"
echo "// SPDX-License-Identifier: LGPL-2.1-or-later"
echo "//! Generated by tools/gen-arphrd-names.sh: \`arphrd_to_name()\`."
echo ""
echo "/// (ARPHRD type, name), by type."
echo "pub const ARPHRD_NAMES: &[(u16, &str)] = &["
"$tmp/a"
echo "];"
