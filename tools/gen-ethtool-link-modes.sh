# gen-ethtool-link-modes.sh - generate crates/shared/src/ethtool_link_modes.rs
#
# 20261116 - Created by Claude (claude.ai, Anthropic) - scottfk
#
# Usage: gen-ethtool-link-modes.sh SYSTEMD_SOURCE_DIR SYSTEMD_BUILD_DIR > ethtool_link_modes.rs
#
# C's ethtool_link_mode_bit_table: the reference build's ethtool-link-mode.inc,
# with the enum values from upstream's bundled kernel headers.
set -eu
src=$1
build=$2
inc=$build/src/shared/ethtool-link-mode.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cat > "$tmp/m.c" <<CEOF
#include <stdio.h>
#include <linux/ethtool.h>
static const char *const t[] = {
#include "$inc"
};
int main(void) {
        for (unsigned i = 0; i < sizeof t / sizeof t[0]; i++)
                if (t[i])
                        printf("    (b\"%s\", %u),\n", t[i], i);
        return 0;
}
CEOF
cc -I "$src/src/include/uapi" -o "$tmp/m" "$tmp/m.c"
echo "// SPDX-License-Identifier: LGPL-2.1-or-later"
echo "//! Generated by tools/gen-ethtool-link-modes.sh: \`ethtool_link_mode_bit_table\`."
echo ""
echo "/// (name, bit) of each ethtool link mode."
echo "pub const LINK_MODES: &[(&[u8], u32)] = &["
"$tmp/m"
echo "];"
